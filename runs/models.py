"""Job records: one execution of a playbook against a set of hosts."""
import json

from django.conf import settings
from django.db import models
from django.urls import reverse
from django.utils import timezone
from django.utils.translation import gettext_lazy as _

from core.crypto import decrypt, encrypt
from inventory.models import Host, HostGroup
from playbooks.models import Playbook


class Job(models.Model):
    PENDING = "pending"
    RUNNING = "running"
    SUCCESSFUL = "successful"
    FAILED = "failed"
    CANCELED = "canceled"
    ERROR = "error"
    STATUS_CHOICES = [
        (PENDING, _("Pending")),
        (RUNNING, _("Running")),
        (SUCCESSFUL, _("Successful")),
        (FAILED, _("Failed")),
        (CANCELED, _("Canceled")),
        (ERROR, _("Error")),
    ]
    FINAL_STATUSES = {SUCCESSFUL, FAILED, CANCELED, ERROR}

    # What started this run.  Everything other than PLAYBOOK is one of Loona's
    # own maintenance runs, generated by inventory.provisioning rather than
    # edited by a user.
    # A plain connection check is not here on purpose: it changes nothing and is
    # answered inside the request by inventory.probe, so it needs no history.
    KIND_PLAYBOOK = "playbook"
    KIND_KEY_INSTALL = "key_install"
    KIND_KEY_VERIFY = "key_verify"
    KIND_KEY_REVOKE = "key_revoke"
    KIND_TOFU_PLAN = "tofu_plan"
    KIND_TOFU_APPLY = "tofu_apply"
    # First playbook on a machine an OpenTofu project created: drops the
    # project's bootstrap key, then runs the project's baseline playbook.
    KIND_BOOTSTRAP = "bootstrap"
    # Loona's own read-only run that only gathers facts.  See inventory.facts.
    KIND_FACTS = "facts"
    # One module run on the targets, typed in rather than kept as a playbook.
    # See runs.adhoc.
    KIND_ADHOC = "adhoc"
    KIND_CHOICES = [
        (KIND_PLAYBOOK, _("Playbook")),
        (KIND_ADHOC, _("Ad-hoc command")),
        (KIND_BOOTSTRAP, _("Bootstrap")),
        (KIND_FACTS, _("Fact gathering")),
        (KIND_TOFU_PLAN, _("OpenTofu plan")),
        (KIND_TOFU_APPLY, _("OpenTofu apply")),
        (KIND_KEY_INSTALL, _("Key install")),
        (KIND_KEY_VERIFY, _("Key verification")),
        (KIND_KEY_REVOKE, _("Key revocation")),
    ]
    SYSTEM_KINDS = {KIND_KEY_INSTALL, KIND_KEY_VERIFY, KIND_KEY_REVOKE}
    TOFU_KINDS = {KIND_TOFU_PLAN, KIND_TOFU_APPLY}

    kind = models.CharField(
        max_length=24, choices=KIND_CHOICES, default=KIND_PLAYBOOK, db_index=True
    )

    playbook = models.ForeignKey(
        Playbook, on_delete=models.SET_NULL, null=True, related_name="jobs"
    )
    # Snapshot so history stays readable after the playbook changes or is deleted.
    playbook_name = models.CharField(max_length=255)
    playbook_yaml = models.TextField()
    # An ad-hoc command as typed; playbook_yaml holds the play made of it.
    adhoc_module = models.CharField(max_length=120, blank=True, default="")
    adhoc_args = models.TextField(blank=True, default="")
    adhoc_become = models.BooleanField(default=False)

    target_hosts = models.ManyToManyField(Host, blank=True, related_name="jobs")
    target_groups = models.ManyToManyField(HostGroup, blank=True, related_name="jobs")
    limit = models.CharField(max_length=255, blank=True, default="")

    extra_vars = models.JSONField(default=dict, blank=True)
    check_mode = models.BooleanField(default=False, help_text=_("Dry run (--check)."))
    diff_mode = models.BooleanField(default=False)
    verbosity = models.PositiveSmallIntegerField(default=0)
    forks = models.PositiveSmallIntegerField(default=5)
    tags = models.CharField(max_length=255, blank=True, default="")
    skip_tags = models.CharField(max_length=255, blank=True, default="")

    status = models.CharField(max_length=16, choices=STATUS_CHOICES, default=PENDING, db_index=True)
    return_code = models.IntegerField(null=True, blank=True)
    stats = models.JSONField(default=dict, blank=True)
    error_message = models.TextField(blank=True, default="")

    # One-off connection variables that must not outlive the run - the login
    # and password typed in to push a key.  Encrypted like any other secret and
    # wiped the moment the runner is done with them.
    connection_override_encrypted = models.TextField(blank=True, default="")
    # Answers to a launch template's password questions: extra vars kept
    # encrypted, never in extra_vars, and wiped once the run that used them
    # is over (a preview keeps them until it is applied).
    secret_vars_encrypted = models.TextField(blank=True, default="")
    launch_template = models.ForeignKey(
        "runs.LaunchTemplate", on_delete=models.SET_NULL, null=True, blank=True, related_name="jobs",
    )
    # An apply points at the preview it carries out.  See runs.plans.
    plan = models.ForeignKey(
        "self",
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="applications",
    )
    # OpenTofu runs.  The project's host group is also the job's target
    # group, which is what makes access.policy apply to them unchanged.
    tofu_project = models.ForeignKey(
        "infra.TofuProject",
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="jobs",
    )
    tofu_destroy = models.BooleanField(default=False)
    # What a plan was made from - a commit, or a digest of Loona-kept files -
    # and, for the latter, the files themselves.  Apply reuses both.
    tofu_revision = models.CharField(max_length=80, blank=True, default="")
    tofu_files = models.JSONField(default=dict, blank=True)
    # The saved plan (tofu plan -out), encrypted: it can hold secrets.
    tofu_plan_encrypted = models.TextField(blank=True, default="")
    # Hash of the one-off password the run uses to reach the state backend.
    state_token_hash = models.CharField(max_length=128, blank=True, default="")
    # The Ansible project a playbook run used, and exactly which version of
    # it: a commit, or a digest of Loona-kept files plus the files themselves.
    ansible_project = models.ForeignKey(
        "playbooks.Project", on_delete=models.SET_NULL, null=True, blank=True, related_name="jobs",
    )
    project_revision = models.CharField(max_length=80, blank=True, default="")
    project_files = models.JSONField(default=dict, blank=True)
    # The catalog request a tofu plan or apply is for.  See catalog.services.
    catalog_request = models.ForeignKey(
        "catalog.CatalogRequest", on_delete=models.SET_NULL, null=True, blank=True, related_name="jobs",
    )
    # The workflow step this run carries out.  See workflows.engine.
    workflow_node = models.ForeignKey(
        "workflows.Node", on_delete=models.SET_NULL, null=True, blank=True, related_name="jobs",
    )
    # Set on the runs a Schedule starts.
    schedule = models.ForeignKey(
        "runs.Schedule", on_delete=models.SET_NULL, null=True, blank=True, related_name="jobs",
    )
    # Set on the check-mode runs a DriftCheck starts on its own.
    drift_check = models.ForeignKey(
        "runs.DriftCheck",
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name="jobs",
    )
    # Inventory names the run actually targeted, groups expanded.  A plan's
    # list is what its apply is held to.
    resolved_hosts = models.JSONField(default=list, blank=True)
    # Which secrets the run was given, as "name (scope)" - never the values.
    secret_names = models.JSONField(default=list, blank=True)
    # Set by a key revocation that is the first half of "delete this host".
    delete_host_on_success = models.BooleanField(default=False)

    private_data_dir = models.CharField(max_length=512, blank=True, default="")
    # "host:pid" of the process driving the run, so a run whose process died
    # can be told apart from one that is merely slow.  See executor.reap_dead_jobs.
    runner = models.CharField(max_length=255, blank=True, default="")
    task_id = models.CharField(max_length=120, blank=True, default="")
    canceled = models.BooleanField(default=False)
    # A run for hosts behind a remote executor: prepared here, then carried
    # out by one of its agents.  The bundle - the prepared run directory,
    # secrets and all - waits encrypted until an agent takes it, and is
    # dropped the moment it does.  See executors.remote.
    executor = models.ForeignKey(
        "executors.Executor", on_delete=models.SET_NULL, null=True, blank=True, related_name="jobs",
    )
    bundle_encrypted = models.TextField(blank=True, default="")
    # The agent's last word on a run it is carrying out.
    heartbeat_at = models.DateTimeField(null=True, blank=True)

    created_by = models.ForeignKey(
        settings.AUTH_USER_MODEL, on_delete=models.SET_NULL, null=True, blank=True
    )
    created_at = models.DateTimeField(auto_now_add=True, db_index=True)
    started_at = models.DateTimeField(null=True, blank=True)
    finished_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        ordering = ["-created_at"]

    def __str__(self):
        return f"#{self.pk} {self.playbook_name}"

    def save(self, *args, **kwargs):
        # Names are composed ("<project>: destroy plan", "Bootstrap <host>:
        # <playbook>"); PostgreSQL refuses an overlong one rather than trim it.
        self.playbook_name = (self.playbook_name or "")[: self._meta.get_field("playbook_name").max_length]
        super().save(*args, **kwargs)

    def get_absolute_url(self):
        return reverse("job_detail", args=[self.pk])

    @property
    def waiting_for_executor(self):
        return self.status == self.PENDING and self.executor_id is not None and self.runner.startswith("executor/")

    @property
    def is_final(self):
        return self.status in self.FINAL_STATUSES

    @property
    def is_plan(self):
        """A preview that can be applied: a check-mode playbook run or a tofu plan."""
        if self.kind == self.KIND_TOFU_PLAN:
            return True
        return self.check_mode and self.kind in (self.KIND_PLAYBOOK, self.KIND_ADHOC)

    @property
    def is_adhoc(self):
        return self.kind == self.KIND_ADHOC

    @property
    def is_tofu(self):
        return self.kind in self.TOFU_KINDS

    @property
    def tofu_plan_file(self) -> bytes:
        import base64

        raw = decrypt(self.tofu_plan_encrypted)
        return base64.b64decode(raw) if raw else b""

    @tofu_plan_file.setter
    def tofu_plan_file(self, data: bytes):
        import base64

        self.tofu_plan_encrypted = encrypt(base64.b64encode(data).decode()) if data else ""

    @property
    def can_be_applied(self):
        return (
            self.is_plan
            and self.status == self.SUCCESSFUL
            and self.plan_has_changes
            and not self.applications.exists()
        )

    @property
    def plan_has_changes(self):
        """False only for a tofu plan that found nothing to do."""
        if self.kind != self.KIND_TOFU_PLAN:
            return True
        return bool((self.stats or {}).get("tofu", {}).get("has_changes"))

    @property
    def is_system(self):
        """True for Loona's own maintenance runs."""
        return self.kind in self.SYSTEM_KINDS

    # -- one-off connection secrets ---------------------------------------
    @property
    def connection_override(self) -> dict:
        raw = decrypt(self.connection_override_encrypted)
        return json.loads(raw) if raw else {}

    @connection_override.setter
    def connection_override(self, value: dict):
        self.connection_override_encrypted = encrypt(json.dumps(value)) if value else ""

    @property
    def secret_vars(self) -> dict:
        raw = decrypt(self.secret_vars_encrypted)
        return json.loads(raw) if raw else {}

    @secret_vars.setter
    def secret_vars(self, value: dict):
        self.secret_vars_encrypted = encrypt(json.dumps(value)) if value else ""

    def forget_secret_vars(self):
        if self.secret_vars_encrypted:
            self.secret_vars_encrypted = ""
            self.save(update_fields=["secret_vars_encrypted"])

    def forget_connection_override(self):
        if self.connection_override_encrypted:
            self.connection_override_encrypted = ""
            self.save(update_fields=["connection_override_encrypted"])

    @property
    def duration(self):
        if not self.started_at:
            return None
        end = self.finished_at or timezone.now()
        return end - self.started_at

    @property
    def host_stats(self):
        """Per-host counters from the ansible-runner stats event."""
        # ansible-runner reports unreachable hosts under "dark".
        keys = {
            "ok": "ok",
            "changed": "changed",
            "unreachable": "dark",
            "failures": "failures",
            "skipped": "skipped",
            "rescued": "rescued",
            "ignored": "ignored",
        }
        hosts = set()
        for stat_key in keys.values():
            hosts.update((self.stats.get(stat_key) or {}).keys())
        rows = []
        for host in sorted(hosts):
            row = {"host": host}
            for name, stat_key in keys.items():
                row[name] = (self.stats.get(stat_key) or {}).get(host, 0)
            row["failed"] = bool(row["failures"] or row["unreachable"])
            rows.append(row)
        return rows

    def mark_running(self, runner=""):
        self.status = self.RUNNING
        self.started_at = timezone.now()
        self.runner = runner
        self.save(update_fields=["status", "started_at", "runner"])

    def mark_finished(self, status, return_code=None, error_message=""):
        self.status = status
        self.return_code = return_code
        self.error_message = error_message or ""
        self.finished_at = timezone.now()
        self.save(
            update_fields=["status", "return_code", "error_message", "finished_at"]
        )


class JobEvent(models.Model):
    """One ansible-runner event, kept so the job log can be replayed."""

    job = models.ForeignKey(Job, on_delete=models.CASCADE, related_name="events")
    counter = models.PositiveIntegerField(default=0)
    uuid = models.CharField(max_length=64, blank=True, default="")
    event = models.CharField(max_length=64, blank=True, default="")
    # Indexed: a host's history is read back through it.
    host = models.CharField(max_length=160, blank=True, default="", db_index=True)
    task = models.CharField(max_length=255, blank=True, default="")
    stdout = models.TextField(blank=True, default="")
    failed = models.BooleanField(default=False)
    changed = models.BooleanField(default=False)
    # What the task changed or would change, as Ansible reports it with --diff.
    diff = models.JSONField(null=True, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["counter", "pk"]
        indexes = [models.Index(fields=["job", "counter"])]

    def __str__(self):
        return f"{self.job_id}:{self.counter} {self.event}"

    @property
    def level(self):
        """CSS class hint for the log viewer."""
        if self.failed or self.event in ("runner_on_failed", "runner_on_unreachable"):
            return "failed"
        if self.event == "runner_on_skipped":
            return "skipped"
        if self.changed:
            return "changed"
        if self.event in ("runner_on_ok", "playbook_on_stats"):
            return "ok"
        return "plain"


class DriftCheck(models.Model):
    """A preview run on a schedule, to notice when reality moves away.

    Either a playbook against a host group - has anyone changed these
    servers by hand? - or an OpenTofu project - has anyone changed the cloud
    behind OpenTofu's back?  Each run is an ordinary preview: it changes
    nothing, and if it finds drift it can be applied to put things back,
    under the same approval rules as any other preview.
    """

    UNKNOWN = "unknown"
    IN_SYNC = "in_sync"
    DRIFTED = "drifted"
    ERROR = "error"
    STATUS_CHOICES = [
        (UNKNOWN, _("Not checked yet")),
        (IN_SYNC, _("In sync")),
        (DRIFTED, _("Drifted")),
        (ERROR, _("Check failed")),
    ]
    INTERVAL_CHOICES = [
        (60, _("Every hour")),
        (360, _("Every 6 hours")),
        (1440, _("Every day")),
        (10080, _("Every week")),
    ]

    name = models.CharField(max_length=160)
    playbook = models.ForeignKey(
        Playbook, on_delete=models.CASCADE, null=True, blank=True, related_name="drift_checks"
    )
    host_group = models.ForeignKey(
        HostGroup, on_delete=models.CASCADE, null=True, blank=True, related_name="drift_checks"
    )
    tofu_project = models.ForeignKey(
        "infra.TofuProject",
        on_delete=models.CASCADE,
        null=True,
        blank=True,
        related_name="drift_checks",
    )
    interval_minutes = models.PositiveIntegerField(choices=INTERVAL_CHOICES, default=1440)
    enabled = models.BooleanField(default=True)
    status = models.CharField(max_length=8, choices=STATUS_CHOICES, default=UNKNOWN)
    status_since = models.DateTimeField(null=True, blank=True)
    # Hosts (playbook checks) or resource addresses (OpenTofu) that drifted.
    drifted = models.JSONField(default=list, blank=True)
    last_job = models.ForeignKey(
        Job, on_delete=models.SET_NULL, null=True, blank=True, related_name="+"
    )
    last_run_at = models.DateTimeField(null=True, blank=True)
    created_by = models.ForeignKey(
        settings.AUTH_USER_MODEL, on_delete=models.SET_NULL, null=True, blank=True
    )
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["name"]

    def __str__(self):
        return self.name

    def get_absolute_url(self):
        return reverse("drift_list")

    @property
    def is_adhoc(self):
        return self.kind == self.KIND_ADHOC

    @property
    def is_tofu(self):
        return self.tofu_project_id is not None

    @property
    def scope_group(self):
        """The group whose roles govern this check."""
        return self.tofu_project.host_group if self.is_tofu else self.host_group

    @property
    def badge(self):
        return {self.IN_SYNC: "ok", self.DRIFTED: "warn", self.ERROR: "fail"}.get(self.status, "")



def _default_zone():
    return settings.TIME_ZONE


class Schedule(models.Model):
    """A playbook started on a cron schedule, as the person who set it up.

    It runs with that person's rights at the moment it fires; if they lose
    them, it stops starting anything and says why.  A run that the targets'
    rules do not allow right now - outside a maintenance window, or on a
    group where every change needs approval - becomes a preview waiting for
    a second person instead.
    """

    RUN = "run"
    PREVIEW = "preview"
    ACTIONS = [(RUN, _("Run (preview instead when approval is needed)")), (PREVIEW, _("Preview only"))]

    name = models.CharField(max_length=160)
    # What it starts: a playbook on host_group, or a workflow (whose own
    # group host_group then is, so the same roles decide who sees it).
    playbook = models.ForeignKey(Playbook, on_delete=models.CASCADE, null=True, blank=True,
                                 related_name="schedules")
    workflow = models.ForeignKey("workflows.Workflow", on_delete=models.CASCADE, null=True, blank=True,
                                 related_name="schedules")
    host_group = models.ForeignKey(HostGroup, on_delete=models.CASCADE, related_name="schedules")
    action = models.CharField(max_length=8, choices=ACTIONS, default=RUN)
    cron = models.CharField(
        _("When"), max_length=120,
        help_text=_("Cron: minute hour day-of-month month day-of-week, e.g. 0 3 * * mon-fri; or @daily."),
    )
    timezone = models.CharField(max_length=64, default=_default_zone)
    limit = models.CharField(max_length=255, blank=True, default="")
    tags = models.CharField(max_length=255, blank=True, default="")
    skip_tags = models.CharField(max_length=255, blank=True, default="")
    extra_vars = models.JSONField(default=dict, blank=True)
    enabled = models.BooleanField(default=True)
    run_as = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name="schedules")
    next_run_at = models.DateTimeField(null=True, blank=True)
    last_run_at = models.DateTimeField(null=True, blank=True)
    last_job = models.ForeignKey(Job, on_delete=models.SET_NULL, null=True, blank=True, related_name="+")
    last_workflow_run = models.ForeignKey("workflows.Run", on_delete=models.SET_NULL, null=True, blank=True,
                                          related_name="+")
    # What happened the last time it was due, when that was not a plain start.
    last_note = models.CharField(max_length=500, blank=True, default="")
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["name"]

    def __str__(self):
        return self.name

    def get_absolute_url(self):
        return reverse("schedule_update", args=[self.pk])

    @property
    def target_name(self) -> str:
        return f"workflow {self.workflow.name}" if self.workflow_id else (self.playbook.name if self.playbook else "?")

    @property
    def last_started(self):
        """The last job or workflow run it started."""
        return self.last_workflow_run if self.workflow_id else self.last_job

    def compute_next(self, after=None):
        from core.cron import Cron, CronError

        try:
            return Cron.parse(self.cron).next_after(after or timezone.now(), self.timezone)
        except (CronError, ValueError, KeyError):
            return None


class LaunchTemplate(models.Model):
    """A playbook ready to launch on a group, with a form for what may vary.

    The survey is a list of questions, each filling one extra variable; a
    launch shows them as a form, so whoever runs it picks a version or a
    service from a list instead of writing YAML.  Password answers never land
    in the job's extra vars.  See runs.surveys.
    """

    name = models.CharField(max_length=160, unique=True)
    description = models.TextField(blank=True, default="")
    playbook = models.ForeignKey(Playbook, on_delete=models.CASCADE, related_name="launch_templates")
    host_group = models.ForeignKey(HostGroup, on_delete=models.CASCADE, related_name="launch_templates")
    extra_vars = models.JSONField(default=dict, blank=True, help_text=_("Fixed; survey answers win over these."))
    limit = models.CharField(max_length=255, blank=True, default="")
    ask_limit = models.BooleanField(_("Let the launcher narrow the hosts"), default=False)
    tags = models.CharField(max_length=255, blank=True, default="")
    skip_tags = models.CharField(max_length=255, blank=True, default="")
    survey = models.JSONField(default=list, blank=True)
    created_by = models.ForeignKey(
        settings.AUTH_USER_MODEL, on_delete=models.SET_NULL, null=True, blank=True, related_name="+"
    )
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ["name"]

    def __str__(self):
        return self.name

    def get_absolute_url(self):
        return reverse("template_launch", args=[self.pk])
